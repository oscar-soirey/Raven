ROOT_ATTRIBUTES = {
    "xmlns": "http://www.w3.org/2000/svg", "width": "24", "height": "24", "viewBox": "0 0 24 24", "fill": "none",
    "stroke": "currentColor", "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round",
}


def shapes_of(path):
    text = open(path, encoding="utf-8").read()
    match = re.search(r"<svg\b([^>]*)>(.*)</svg>", text, re.S)
    if not match:
        sys.exit("%s: no <svg> element" % path)
    attributes = dict(re.findall(r'([\w:-]+)="([^"]*)"', match.group(1)))
    attributes.pop("class", None)
    if attributes != ROOT_ATTRIBUTES:
        sys.exit("%s: the <svg> element is not the one of every Lucide icon: %s" % (path, attributes))
    body = match.group(2)
    if "<!--" in body or "<text" in body or "<image" in body or "url(" in body:
        sys.exit("%s: comments, text, images or gradients" % path)
    # one shape after the other, with one space between attributes
    body = re.sub(r"\s+", " ", body).strip()
    body = re.sub(r"\s*/>\s*", "/>", body)
    body = re.sub(r">\s+<", "><", body)
    if '"' in body.replace('="', "").replace('" ', "").replace('"/>', "").replace('">', ""):
        sys.exit("%s: unexpected quotes" % path)
    return body


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) > 1:
        os.makedirs(FOLDER, exist_ok=True)
        for old in os.listdir(FOLDER):
            os.remove(os.path.join(FOLDER, old))
        for lucide in sorted(set(ICONS.values())):
            shutil.copy(os.path.join(sys.argv[1], lucide + ".svg"), os.path.join(FOLDER, lucide + ".svg"))
    names = sorted(ICONS)
    rows = []
    total = 0
    for name in names:
        body = shapes_of(os.path.join(FOLDER, ICONS[name] + ".svg"))
        total += len(body) + 1
        rows.append("\t{ %s, %s }," % (c_string(name), c_string(body)))
    with open(TARGET, "w", encoding="utf-8", newline="\n") as out:
        out.write("/**\n * Generated by tools/embed_icons.py - do not edit.\n"
                  " * Icons of Lucide (third_party/lucide), ISC License, partly MIT (Feather) - see third_party/lucide/LICENSE\n"
                  " * The shapes inside the <svg> element of each icon (%d icons, %d bytes), sorted by name.\n */\n\n" % (len(names), total))
        out.write('#include "../render/icons.h"\n\n')
        out.write("const rvn_icon_source_t rvn_icon_sources[] = {\n%s\n};\n\n" % "\n".join(rows))
        out.write("const int rvn_icon_source_count = %d;\n" % len(names))
    print("%d icons, %d bytes of shapes" % (len(names), total))


if __name__ == "__main__":
    main()
