#!/usr/bin/env python3
"""Turns the icons of third_party/lucide/icons into src/resources/icons.c.

    python3 tools/embed_icons.py [lucide-static/icons]

With a folder of the lucide-static package, first copies the icons of ICONS
from it into third_party/lucide/icons (to update them). Then embeds them.

Every Lucide icon is the same <svg> element (24 x 24, no fill, a stroke of 2
in currentColor, round caps and joins) around a few shapes: only the shapes
are kept, without white space between them; Raven puts the <svg> element back
around them (src/render/icons.c). An icon whose <svg> element is not that one
stops the script.
"""
