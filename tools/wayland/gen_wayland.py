#!/usr/bin/env python3
"""
Raven - tools/wayland/gen_wayland.py
Writes src/platform/wayland/wayland_protocols.h from the protocol files of
third_party/wayland-protocols, as wayland-scanner would, with two differences:

  - everything is `static`: the interfaces are private copies, so that they
    never clash with the ones of libwayland-client when a program links it
    too (libwayland only reads their names, versions and signatures);
  - the requests call libwayland-client through macros (RVN_WL_MARSHAL...)
    that wayland_platform.c points at the library it opened with dlopen:
    Raven builds without the development files of Wayland.

    python3 tools/wayland/gen_wayland.py

Run it after adding a protocol file to the list below; the file it writes is
checked in, like the compiled shaders.
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROTOCOLS = os.path.join(ROOT, "third_party", "wayland-protocols")
OUTPUT = os.path.join(ROOT, "src", "platform", "wayland", "wayland_protocols.h")

FILES = [
    "wayland.xml",
    "xdg-shell.xml",
    "xdg-decoration-unstable-v1.xml",
    "viewporter.xml",
    "fractional-scale-v1.xml",
    "cursor-shape-v1.xml",
    "ext-background-effect-v1.xml",
    "xdg-toplevel-icon-v1.xml",
]

C_TYPES = {
    "int": "int32_t",
    "uint": "uint32_t",
    "fixed": "int32_t",
    "string": "const char*",
    "array": "struct wl_array*",
    "fd": "int32_t",
}
SIGNATURE = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o",
             "new_id": "n", "array": "a", "fd": "h"}


class Arg:
    def __init__(self, node):
        self.name = node.get("name")
        self.type = node.get("type")
        self.interface = node.get("interface")
        self.nullable = node.get("allow-null") == "true"
        if self.name in ("default", "interface", "class", "id") and self.type != "new_id":
            pass
        self.cname = self.name + "_" if self.name in ("default", "class", "interface") else self.name


class Message:
    def __init__(self, node, opcode):
        self.name = node.get("name")
        self.opcode = opcode
        self.since = int(node.get("since", "1"))
        self.destructor = node.get("type") == "destructor"
        self.args = [Arg(a) for a in node.findall("arg")]

    def signature(self):
        out = str(self.since) if self.since > 1 else ""
        for a in self.args:
            if a.nullable:
                out += "?"
            if a.type == "new_id" and not a.interface:
                out += "sun"
            else:
                out += SIGNATURE[a.type]
        return out

    def types(self):
        out = []
        for a in self.args:
            if a.type == "new_id" and not a.interface:
                out += [None, None, None]
            elif a.type in ("object", "new_id"):
                out.append(a.interface)
            else:
                out.append(None)
        return out


class Interface:
    def __init__(self, node):
        self.name = node.get("name")
        self.version = int(node.get("version"))
        self.requests = [Message(n, i) for i, n in enumerate(node.findall("request"))]
        self.events = [Message(n, i) for i, n in enumerate(node.findall("event"))]
        self.enums = []
        for e in node.findall("enum"):
            entries = [(x.get("name"), x.get("value")) for x in e.findall("entry")]
            self.enums.append((e.get("name"), entries))


def load():
    interfaces = []
    for name in FILES:
        tree = ET.parse(os.path.join(PROTOCOLS, name))
        for node in tree.getroot().findall("interface"):
            interfaces.append(Interface(node))
    return interfaces


def iface_ref(name, known):
    return "&rvn_%s_interface" % name if name in known else "NULL"


def c_arg(arg, known):
    if arg.type == "object":
        return "struct %s*" % arg.interface if arg.interface else "void*"
    if arg.type == "new_id":
        return "struct %s*" % arg.interface
    return C_TYPES[arg.type]


def generate(interfaces):
    known = {i.name for i in interfaces}
    o = []
    w = o.append
    w("/**")
    w(" * Raven - platform/wayland/wayland_protocols.h")
    w(" * Generated by tools/wayland/gen_wayland.py from third_party/wayland-protocols: do not edit.")
    w(" *")
    w(" * The interfaces of the protocols Raven speaks, and their requests, events")
    w(" * and enumerations. Included once, by wayland_platform.c, after it defined")
    w(" * the RVN_WL_* macros that reach libwayland-client.")
    w(" */")
    w("")
    w("#ifndef RVN_WAYLAND_PROTOCOLS_H")
    w("#define RVN_WAYLAND_PROTOCOLS_H")
    w("")
    w("/* (some interfaces have requests Raven never sends) */")
    w("#if defined(__GNUC__)")
    w("#pragma GCC diagnostic push")
    w("#pragma GCC diagnostic ignored \"-Wunused-function\"")
    w("#endif")
    w("")
    referenced = set()
    for i in interfaces:
        for m in i.requests + i.events:
            referenced.update(a.interface for a in m.args if a.interface)
    for name in sorted(referenced - known):
        w("struct %s;   /* (from a protocol Raven does not use) */" % name)
    for i in interfaces:
        w("struct %s;" % i.name)
    w("")
    for i in interfaces:
        w("static const struct wl_interface rvn_%s_interface;" % i.name)
    w("")

    # types and messages
    for i in interfaces:
        for kind, messages in (("requests", i.requests), ("events", i.events)):
            for m in messages:
                types = m.types()
                if types:
                    w("static const struct wl_interface* rvn_types_%s_%s_%s[] = { %s };" % (
                        i.name, kind[0], m.name, ", ".join(iface_ref(t, known) if t else "NULL" for t in types)))
            if messages:
                w("static const struct wl_message rvn_%s_%s[] = {" % (i.name, kind))
                for m in messages:
                    types = "rvn_types_%s_%s_%s" % (i.name, kind[0], m.name) if m.types() else "NULL"
                    w("\t{ \"%s\", \"%s\", %s }," % (m.name, m.signature(), types))
                w("};")
        w("static const struct wl_interface rvn_%s_interface = {" % i.name)
        w("\t\"%s\", %d," % (i.name, i.version))
        w("\t%d, %s," % (len(i.requests), "rvn_%s_requests" % i.name if i.requests else "NULL"))
        w("\t%d, %s" % (len(i.events), "rvn_%s_events" % i.name if i.events else "NULL"))
        w("};")
        w("")

    # enumerations
    for i in interfaces:
        for ename, entries in i.enums:
            w("enum %s_%s {" % (i.name, ename))
            for n, v in entries:
                ident = ("%s_%s_%s" % (i.name, ename, n)).upper()
                w("\t%s = %s," % (ident, v))
            w("};")
    w("")

    # listeners
    for i in interfaces:
        if not i.events or i.name == "wl_display":
            continue
        w("struct %s_listener {" % i.name)
        for m in i.events:
            params = ["void* data", "struct %s* %s" % (i.name, i.name)]
            params += ["%s %s" % (c_arg(a, known), a.cname) for a in m.args]
            w("\tvoid (*%s)(%s);" % (m.name, ", ".join(params)))
        w("};")
        w("static int %s_add_listener(struct %s* %s, const struct %s_listener* listener, void* data) {" % (
            i.name, i.name, i.name, i.name))
        w("\treturn RVN_WL_ADD_LISTENER((struct wl_proxy*)%s, (void (**)(void))listener, data);" % i.name)
        w("}")
    w("")

    # requests
    for i in interfaces:
        w("static void %s_set_user_data(struct %s* %s, void* data) { RVN_WL_SET_USER_DATA((struct wl_proxy*)%s, data); }" % (
            i.name, i.name, i.name, i.name))
        w("static void* %s_get_user_data(struct %s* %s) { return RVN_WL_GET_USER_DATA((struct wl_proxy*)%s); }" % (
            i.name, i.name, i.name, i.name))
        w("static uint32_t %s_get_version(struct %s* %s) { return RVN_WL_GET_VERSION((struct wl_proxy*)%s); }" % (
            i.name, i.name, i.name, i.name))
        names = [m.name for m in i.requests]
        if "destroy" not in names and i.name != "wl_display":
            w("static void %s_destroy(struct %s* %s) { RVN_WL_PROXY_DESTROY((struct wl_proxy*)%s); }" % (
                i.name, i.name, i.name, i.name))
        for m in i.requests:
            new_id = [a for a in m.args if a.type == "new_id"]
            params = ["struct %s* %s" % (i.name, i.name)]
            call = []
            if new_id and not new_id[0].interface:
                ret = "void*"
                for a in m.args:
                    if a.type == "new_id":
                        params += ["const struct wl_interface* interface_", "uint32_t version"]
                        call += ["interface_->name", "version", "NULL"]
                    else:
                        params.append("%s %s" % (c_arg(a, known), a.cname))
                        call.append(a.cname)
                target, version = "interface_", "version"
            else:
                ret = "struct %s*" % new_id[0].interface if new_id else "void"
                for a in m.args:
                    if a.type == "new_id":
                        call.append("NULL")
                    else:
                        params.append("%s %s" % (c_arg(a, known), a.cname))
                        call.append(a.cname)
                target = iface_ref(new_id[0].interface, known) if new_id else "NULL"
                version = "RVN_WL_GET_VERSION((struct wl_proxy*)%s)" % i.name
            flags = "RVN_WL_MARSHAL_FLAG_DESTROY" if m.destructor else "0"
            body = "RVN_WL_MARSHAL((struct wl_proxy*)%s, %d, %s, %s, %s%s)" % (
                i.name, m.opcode, target, version, flags, "".join(", " + c for c in call))
            w("static %s %s_%s(%s) {" % (ret, i.name, m.name, ", ".join(params)))
            if ret == "void":
                w("\t%s;" % body)
            else:
                w("\treturn (%s)%s;" % (ret, body))
            w("}")
        w("")

    w("#if defined(__GNUC__)")
    w("#pragma GCC diagnostic pop")
    w("#endif")
    w("")
    w("#endif /* RVN_WAYLAND_PROTOCOLS_H */")
    return "\n".join(o) + "\n"


def main():
    text = generate(load())
    check = "--check" in sys.argv
    if check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != text:
            print("wayland_protocols.h is not up to date: run tools/wayland/gen_wayland.py")
            return 1
        return 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUTPUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
