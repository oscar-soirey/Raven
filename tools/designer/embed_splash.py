#!/usr/bin/env python3
"""
Raven Designer - embed_splash.py
Embeds the splash screen in the program, like tools/embed.py does for the fonts:

    splash.xml              -> splash_xml.c   (ds_splash_xml_data / ds_splash_xml_size)
    images/SplashScreenNew.png -> splash_png.c   (ds_splash_png_data / ds_splash_png_size)

Run it from the designer folder whenever one of the two files changes:

    python3 embed_splash.py            writes the two .c files
    python3 embed_splash.py --check    writes nothing, exits 1 when they are out of date

Wire it in the build so that it runs before the compilation (see splash.c).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

JOBS = [
    ("splash.xml", "splash_xml.c", "ds_splash_xml", True,
     "The splash screen window (splash.xml)"),
    (os.path.join("images", "SplashScreenNew.png"), "splash_png.c", "ds_splash_png", False,
     "The picture of the splash screen (images/SplashScreenNew.png), a PNG"),
]


def render(source, name, text_mode, what):
    with open(os.path.join(HERE, source), "rb") as f:
        data = f.read()
    size = len(data)
    if text_mode:
        data = data.replace(b"\r\n", b"\n") + b"\0"   # (a terminating 0 that the size does not count)
    out = ["/**\n", " * Generated by embed_splash.py - do not edit.\n", " * %s\n" % what, " */\n\n",
           "#include <stddef.h>\n\n", "const unsigned char %s_data[] = {\n" % name]
    for i in range(0, len(data), 20):
        out.append("\t" + ",".join(str(b) for b in data[i:i + 20]) + ("," if i + 20 < len(data) else "") + "\n")
    if text_mode:
        size = len(data) - 1
    out.append("};\n\n")
    out.append("const size_t %s_size = %d;\n" % (name, size))
    return "".join(out)


def main():
    check = "--check" in sys.argv[1:]
    stale = False
    for source, target, name, text_mode, what in JOBS:
        text = render(source, name, text_mode, what)
        path = os.path.join(HERE, target)
        old = None
        if os.path.exists(path):
            with open(path, "r", newline="") as f:
                old = f.read()
        if old != text:
            stale = True
            if not check:
                with open(path, "w", newline="") as f:
                    f.write(text)
                print("wrote", target)
    if check and stale:
        print("splash_xml.c / splash_png.c are out of date: run embed_splash.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
