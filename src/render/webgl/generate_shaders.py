#!/usr/bin/env python3
"""Adapt Raven's reference analytic shaders to GLSL ES 3.00."""
from pathlib import Path
import json
import re

root = Path(__file__).resolve().parents[3]
output = []
for stage in ("vert", "frag"):
    source = (root / f"src/render/vulkan/shaders/ui.{stage}").read_text()
    source = source.replace(
        "#version 450",
        "#version 300 es\nprecision highp float;\n"
        "precision highp int;\nprecision highp sampler2D;")
    if stage == "vert":
        source = re.sub(
            r"layout\(push_constant\) uniform PushConstants \{.*?\} pc;",
            "struct PushConstants { vec2 scale; vec2 translate; "
            "vec2 pointer; vec2 unused; };\nuniform PushConstants pc;",
            source, flags=re.S)
        source = source.replace("gl_VertexIndex", "gl_VertexID")
        source = source.replace("v_inv_size = pc.scale * 0.5;",
                                "v_inv_size = abs(pc.scale) * 0.5;")
    else:
        source = source.replace(
            "vec2 p = gl_FragCoord.xy;",
            "vec2 p = vec2(gl_FragCoord.x, "
            "1.0 / v_inv_size.y - gl_FragCoord.y);")
        source = source.replace(
            "vec4 texel = textureGrad(u_texture, v_uv, uv_dx, uv_dy);",
            "vec4 texel = textureGrad(u_texture, v_uv, uv_dx, uv_dy);\n"
            "        if (u_alpha_only) texel = vec4(1.0, 1.0, 1.0, texel.r);")
        source = source.replace("uniform sampler2D u_texture;",
                                "uniform sampler2D u_texture;\n"
                                "uniform bool u_alpha_only;")
        # Every textureLod in the reference fragment shader samples a backdrop.
        source = source.replace("textureLod(", "backdrop_sample(")
        at = source.index("/* Rounded box")
        source = source[:at] + (
            "vec4 backdrop_sample(sampler2D image, vec2 uv, float lod) {\n"
            "    return textureLod(image, vec2(uv.x, 1.0 - uv.y), lod);\n"
            "}\n\n") + source[at:]
    source = re.sub(r"layout\(set = \d+, binding = \d+\) ", "", source)

    def varying(match):
        qualifier, direction = match.group(1) or "", match.group(2)
        if stage == "vert" and direction == "in":
            return match.group(0)
        if stage == "frag" and direction == "out":
            return match.group(0)
        return qualifier + direction

    source = re.sub(r"layout\(location = \d+\) (flat )?(in|out)",
                    varying, source)
    output.append(f"static const char rvn_webgl_{stage}[] =\n" +
                  "\n".join(json.dumps(line + "\n")
                            for line in source.splitlines()) + ";\n")
Path(__file__).with_name("shaders.h").write_text(
    "/* Generated by generate_shaders.py; do not edit. */\n" + "".join(output))

# Effects share the reference effect ABI; only platform GLSL syntax differs.
common = (root / "include/raven/shaders/raven_effect.glsl").read_text()
common = re.sub(r"layout\(set = \d+, binding = \d+\) ", "", common)
common = re.sub(r"layout\(location = \d+\) (flat )?in",
                lambda m: (m.group(1) or "") + "in", common)
names = {"rvn_v_uv": "v_uv", "rvn_v_rect": "v_rect",
         "rvn_v_clip": "v_clip", "rvn_v_radii": "v_radii",
         "rvn_v_color2": "v_border_color", "rvn_v_color": "v_color",
         "rvn_v_time": "v_border_width", "rvn_v_flags": "v_flags",
         "rvn_v_params": "v_params", "rvn_v_inv_size": "v_inv_size",
         "rvn_v_pointer": "v_pointer", "rvn_texture": "u_texture",
         "rvn_backdrop_blur": "u_backdrop_blur", "rvn_backdrop": "u_backdrop"}
for old, new in names.items():
    common = common.replace(old, new)
common = common.replace("vec2 p = gl_FragCoord.xy;",
                        "vec2 p = vec2(gl_FragCoord.x, "
                        "1.0 / v_inv_size.y - gl_FragCoord.y);")
common = common.replace("screen * v_inv_size",
                        "vec2(screen.x * v_inv_size.x, "
                        "1.0 - screen.y * v_inv_size.y)")
preamble = ("#version 300 es\nprecision highp float;\n"
            "precision highp int;\nprecision highp sampler2D;\n")

def c_string(name, source):
    return f"static const char {name}[] =\n" + "\n".join(
        json.dumps(line + "\n") for line in source.splitlines()) + ";\n"

effects = ["aurora", "shimmer", "neon", "ripple", "plasma", "grain",
           "spotlight", "mesh"]
result = c_string("rvn_webgl_effect_common", preamble + common)
for effect in effects:
    body = (root / f"src/render/vulkan/shaders/effects/{effect}.frag").read_text()
    body = re.sub(r"^#(version|extension|include).*\n", "", body,
                  flags=re.M)
    result += c_string(f"rvn_webgl_effect_{effect}", body)
result += "static const char* const rvn_webgl_effects[] = {\n"
result += ",\n".join(f"    rvn_webgl_effect_{effect}" for effect in effects)
result += "\n};\n"
Path(__file__).with_name("effects.h").write_text(
    "/* Generated by generate_shaders.py; do not edit. */\n" + result)
