#!/usr/bin/env python3
"""
Raven - src/render/metal/generate_shaders.py
Writes src/render/metal/generated/shaders.h: every Metal Shading Language
source of src/render/metal/shaders as a C string, which the Metal backend
compiles at run time (newLibraryWithSource). The offline compiler only comes
with the full Xcode; compiling the sources when the backend starts keeps the
build free of it.

    python3 src/render/metal/generate_shaders.py                  write the header
    python3 src/render/metal/generate_shaders.py --check          exit 1 when it is not up to date
    python3 src/render/metal/generate_shaders.py --allow-missing  a missing effect becomes ""

Run it after changing a .metal file; the header it writes is checked in, like
the compiled shaders of the Vulkan backend (docs/METAL_BACKEND.md).
"""

import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SHADERS = os.path.join(HERE, "shaders")
OUTPUT = os.path.join(HERE, "generated", "shaders.h")

# what Raven puts around the effects, in the order of docs/METAL_BACKEND.md
CORE = ("common", "ui", "blur", "effect")
# the built-in effects, in the order of REffect (raven_shader.h)
EFFECTS = ("aurora", "shimmer", "neon", "ripple", "plasma", "grain", "spotlight", "mesh")


def c_string(text):
    """The source as a C string literal, one line of the file per line of C."""
    if any(ord(c) > 127 for c in text):
        raise ValueError("not ASCII")
    lines = text.replace("\r\n", "\n").replace("\r", "\n").splitlines()
    if not lines:
        return '""'
    # json.dumps escapes \, " and the control characters as C does; "??" is
    # broken up so that no trigraph is read in a strict C11 build
    return "\n".join(json.dumps(line + "\n").replace("??", "?\\?") for line in lines)


def load(path, allow_missing):
    if not os.path.exists(path):
        if allow_missing:
            return ""
        raise FileNotFoundError(path)
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def generate(allow_missing):
    # every effect file is embedded: one that is not in the list (a new effect
    # added to REffect) must be added to EFFECTS, never left out silently
    found = sorted(os.path.splitext(os.path.basename(p))[0]
                   for p in glob.glob(os.path.join(SHADERS, "effects", "*.metal")))
    unknown = [name for name in found if name not in EFFECTS]
    if unknown:
        raise ValueError("effects/%s.metal is not in EFFECTS (in the order of REffect)" % unknown[0])

    files = [(name, "rvn_mtl_%s_source" % name, os.path.join(SHADERS, name + ".metal")) for name in CORE]
    files += [(name, "rvn_mtl_effect_%s_source" % name, os.path.join(SHADERS, "effects", name + ".metal"))
              for name in EFFECTS]

    o = []
    o.append("/* Generated by generate_shaders.py from src/render/metal/shaders; do not edit. */")
    o.append("#ifndef RVN_MTL_SHADERS_H")
    o.append("#define RVN_MTL_SHADERS_H")
    o.append("")
    for name, symbol, path in files:
        rel = os.path.relpath(path, SHADERS).replace(os.sep, "/")
        try:
            text = c_string(load(path, allow_missing))
        except ValueError:
            raise ValueError("shaders/%s: the sources must be ASCII" % rel)
        o.append("/* shaders/%s */" % rel)
        o.append("static const char %s[] =" % symbol)
        o.append(text + ";")
        o.append("")
    o.append("#define RVN_MTL_EFFECT_COUNT %d" % len(EFFECTS))
    o.append("/* in the order of REffect: %s */" % ", ".join(EFFECTS))
    o.append("static const char* const rvn_mtl_effect_sources[RVN_MTL_EFFECT_COUNT] = {")
    o.append(",\n".join("\trvn_mtl_effect_%s_source" % name for name in EFFECTS))
    o.append("};")
    o.append("")
    o.append("#endif")
    return "\n".join(o) + "\n"


def main():
    check = "--check" in sys.argv
    try:
        text = generate("--allow-missing" in sys.argv)
    except (FileNotFoundError, ValueError) as error:
        print("generate_shaders.py: %s" % error, file=sys.stderr)
        return 1
    if check:
        current = ""
        if os.path.exists(OUTPUT):
            with open(OUTPUT, encoding="utf-8", newline="") as f:
                current = f.read()
        if current != text:
            print("src/render/metal/generated/shaders.h is not up to date: run src/render/metal/generate_shaders.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUTPUT, ROOT).replace(os.sep, "/"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
