#!/usr/bin/env python3
"""Writes sg_prefix.h: every public function of sokol_gfx.h gets the prefix rvn_sokol_ so the copy compiled
into Raven cannot clash with an application's own sokol (the types are not linker symbols)."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
header = os.path.join(here, "..", "..", "..", "third_party", "sokol", "sokol_gfx.h")
names = sorted(set(re.findall(r"^SOKOL_GFX_API_DECL\s+[^;(]*?\b(sg_[a-z0-9_]+)\s*\(", open(header).read(), re.M)))
out = ["/* generated by gen_prefix.py from third_party/sokol/sokol_gfx.h: do not edit */",
       "#ifndef RVN_SG_PREFIX_H", "#define RVN_SG_PREFIX_H", ""]
out += [f"#define {n} rvn_sokol_{n}" for n in names]
out += ["", "#endif", ""]
open(os.path.join(here, "sg_prefix.h"), "w").write("\n".join(out))
print(len(names), "functions")
