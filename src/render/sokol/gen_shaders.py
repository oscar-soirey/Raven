#!/usr/bin/env python3
"""Generates the shader sources of the Sokol backend from the Vulkan GLSL of src/render/vulkan/shaders.

    glslangValidator -> SPIR-V -> spirv-cross -> GLSL ES 3.00 (GLES3 / WebGL2) and MSL (Metal)

Run it when a shader changes (needs glslang and spirv-cross; the outputs are committed, like the
SPIR-V headers of the Vulkan backend). More targets (HLSL, GLSL 4.10) are added to TARGETS.

Per-target adjustments, all because the graphics APIs disagree about where the origin is:
 - Metal (and D3D11, WebGPU) have the origin at the top left but NDC y pointing up, the reverse of Vulkan.
   The backend flips y in the transform (scale.y < 0), so ui.vert takes abs() of the scale for the backdrop
   coordinates, and blur.vert reads its source with v = 1 - y.
 - MSL gives every texture its own [[texture(n)]]: the descriptor bindings of ui.frag and of the effects
   (set 0 binding 0 = texture, set 1 bindings 0 and 1 = backdrops) are remapped to bindings 0, 1, 2 of set 0.

 - ui.vert / ui.frag are used unmodified.
 - blur.frag keeps a vec2 and an int in its push constants; SPIRV-Cross cannot flatten that for GL,
   so they are packed into one vec4 (xy = step, z = mode) in a patched copy.
 - Effects (raven_effect.glsl) are translated from the SPIR-V embedded in the Vulkan backend. GLES 3.0
   and WebGL2 link varyings by name, so the fragment inputs are renamed, by location, to the names of
   the ui.vert outputs. Each built-in is keyed by a hash of its SPIR-V (what CreateShader receives).
"""
import os, re, struct, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
VK = os.path.join(ROOT, "src", "render", "vulkan")
OUT = os.path.join(HERE, "generated")
TARGETS = {
    "es300": ["--version", "300", "--es", "--flatten-ubo", "--glsl-emit-push-constant-as-ubo"],
    "msl": ["--msl", "--msl-version", "20100", "--msl-decoration-binding"],
}
# text edits of the Vulkan GLSL for one target: {target: {shader: [(old, new), ...]}}
PATCHES = {
    "msl": {
        "ui.vert": [("pc.scale * 0.5", "abs(pc.scale) * 0.5")],
        "blur.vert": [("v_uv = corner;", "v_uv = vec2(corner.x, 1.0 - corner.y);")],
    },
}
VARYINGS = ["v_uv", "v_rect", "v_clip", "v_radii", "v_color", "v_border_color", "v_border_width", "v_flags", "v_params", "v_inv_size", "v_pointer"]
EFFECTS = ["aurora", "shimmer", "neon", "ripple", "plasma", "grain", "spotlight", "mesh"]

def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout

def fnv(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

# the C macro that selects each target in the build (sg_impl.c)
MACROS = {"es300": "RAVEN_SOKOL_GLES3", "msl": "RAVEN_SOKOL_METAL"}

def c_string(name, text, target=None):
    lit = "".join('\t"%s\\n"\n' % l.replace("\\", "\\\\").replace('"', '\\"') for l in text.splitlines())
    guard = f"#if defined({MACROS[target]})\n" if target else ""
    end = "#endif\n" if target else ""
    return f"{guard}static const char {name}[] =\n{lit};\n{end}"

def cross(spv, target, extra=()):
    return run("spirv-cross", spv, *TARGETS[target], *extra)

def remap_descriptors(data):
    """MSL: set 0 binding 0 stays, set 1 bindings 0 and 1 become bindings 1 and 2 of set 0 (SPIR-V words)."""
    words = list(struct.unpack("<%dI" % (len(data) // 4), data))
    at, info = 5, {}
    while at < len(words):
        count, opcode = words[at] >> 16, words[at] & 0xFFFF
        if opcode == 71 and words[at + 2] in (33, 34):          # OpDecorate: Binding / DescriptorSet
            info.setdefault(words[at + 1], {})[words[at + 2]] = (at, words[at + 3])
        at += max(count, 1)
    for ident, d in info.items():
        if 33 in d and 34 in d:
            set_at, set_value = d[34]
            bind_at, bind_value = d[33]
            words[bind_at + 3] = bind_value + (1 if set_value == 1 else 0)
            words[set_at + 3] = 0
    return struct.pack("<%dI" % len(words), *words)

def compile_glsl(path, patches, out):
    text = open(path).read()
    for old, new in patches:
        assert old in text, (path, old)
        text = text.replace(old, new)
    # (glslang takes the stage from the extension: keep the one of the source)
    patched = os.path.splitext(out)[0] + os.path.splitext(path)[1]
    open(patched, "w").write(text)
    run("glslangValidator", "-V", patched, "-o", out)
    return out

def main():
    os.makedirs(OUT, exist_ok=True)
    tmp = tempfile.mkdtemp()
    shaders = ["/* generated by gen_shaders.py: do not edit */\n"]
    for target in TARGETS:
        for name, src in (("ui_vert", "ui.vert"), ("ui_frag", "ui.frag"), ("blur_vert", "blur.vert"), ("blur_frag", "blur.frag")):
            patches = list(PATCHES.get(target, {}).get(src, []))
            if name == "blur_frag":
                # a vec2 and an int cannot be flattened for GL: one vec4 (xy = step, z = mode, w = flip), in every target
                patches += [("vec2 step;", "vec4 p;"), ("int mode;", ""), ("pc.step", "pc.p.xy"), ("pc.mode", "int(pc.p.z + 0.5)")]
                # the copy (mode 2) can flip the image: presenting to a GL window, whose origin is the bottom left (p.w = 1)
                patches += [("out_color = textureLod(u_source, v_uv, 0.0);", "out_color = textureLod(u_source, vec2(v_uv.x, mix(v_uv.y, 1.0 - v_uv.y, pc.p.w)), 0.0);")]
            spv = compile_glsl(os.path.join(VK, "shaders", src), patches, os.path.join(tmp, f"{name}_{target}.spv"))
            if target == "msl" and name == "ui_frag":
                data = remap_descriptors(open(spv, "rb").read())
                spv = os.path.join(tmp, "ui_frag_msl_remapped.spv")
                open(spv, "wb").write(data)
            shaders.append(c_string(f"rvn_sg_{name}_{target}", cross(spv, target), target))
    open(os.path.join(OUT, "sg_shaders.h"), "w").write("\n".join(shaders))

    fx = ["/* generated by gen_shaders.py: do not edit */\n"]
    table = []
    for name in EFFECTS:
        text = open(os.path.join(VK, "generated", f"effect_{name}_spv.h")).read()
        words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]{8}", text)]
        data = struct.pack("<%dI" % len(words), *words)
        for target in TARGETS:
            spv = os.path.join(tmp, f"fx_{name}_{target}.spv")
            extra = []
            if target == "msl":
                open(spv, "wb").write(remap_descriptors(data))
            else:
                open(spv, "wb").write(data)
                # GLES 3.0 / WebGL2 link varyings by name: the fragment inputs get the names of ui.vert's outputs
                for loc, n in enumerate(VARYINGS):
                    extra += ["--rename-interface-variable", "in", str(loc), n]
            fx.append(c_string(f"rvn_sg_fx_{name}_{target}", cross(spv, target, extra), target))
        table.append((name, fnv(data)))
    fx.append("/* hash (FNV-1a 64) of the SPIR-V of each built-in effect, and its variant for each target */")
    # one `source` per entry: the variant of the target this library is built for
    fx.append("static const struct { const char* name; uint64_t hash; const char* source; } rvn_sg_effects[] = {")
    for name, h in table:
        for target in TARGETS:
            fx.append(f"#if defined({MACROS[target]})")
            fx.append(f'\t{{ "{name}", 0x{h:016x}ull, rvn_sg_fx_{name}_{target} }},')
            fx.append("#endif")
    fx.append("};\n")
    open(os.path.join(OUT, "sg_effects.h"), "w").write("\n".join(fx))
    print("wrote", os.path.join(OUT, "sg_shaders.h"), "and sg_effects.h")

if __name__ == "__main__":
    main()
